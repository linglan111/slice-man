async function seekFrame(page: Page, seconds: number): Promise<void> {
  const video = page.locator('video');
  const before = await video.evaluate((element: HTMLVideoElement) => Number(element.dataset.frameCount ?? '0'));
  await video.evaluate((element: HTMLVideoElement, target) => { element.currentTime = target; }, seconds);
  await expect.poll(() => video.evaluate((element: HTMLVideoElement) => element.seeking)).toBe(false);
  await expect.poll(() => video.evaluate((element: HTMLVideoElement) => Number(element.dataset.frameCount ?? '0'))).toBeGreaterThan(before);
  await expect.poll(() => video.evaluate((element: HTMLVideoElement, target) => Math.abs(Number(element.dataset.frameTime ?? '-1000') - target), seconds)).toBeLessThan(.05);
  expect(await video.evaluate((element: HTMLVideoElement) => element.currentTime)).toBeCloseTo(seconds, 2);
}

